/**
 * 消費税の扱いを1か所にまとめる。
 *
 * ■ どの数字が税抜で、どの数字が税込か
 *
 * 保存している金額は、出どころによって基準が違う。
 *
 *   受注の決済額（orders.amount）… 税込。
 *     UTAGE・Stripe が実際にお客様から預かった額そのもの。
 *     ここを税抜で保存し直すことはできない（預かった額が変わるわけではない）。
 *
 *   支払額（agencies.pay_unit）… 税抜。
 *     2026-08 会議「金額は税抜きで統一」に沿って、はじめから税抜で持っている。
 *     支払通知書は、この額に消費税を足して総額を出している。
 *
 *   商品マスタの単価と報酬（products）… 税抜へ移行中。
 *     もともと税込で入っていたが、税別表示に合わせて入れ替える。
 *     列名は price_incl_tax のままなので、名前で判断しないこと。
 *
 * ■ ここにある関数の使いどころ
 *
 * 画面に税別で出すのは「税込で保存しているもの」だけ。
 * はじめから税抜のもの（支払額・支払通知書）に使うと二重に割ることになり、
 * 相手に渡る書面の支払額が実際より少なくなる。
 */

/** 消費税率。軽減税率の対象商品は無い。 */
export const TAX_RATE = 0.1;

/**
 * 税込の額から税別の額を出す。
 *
 * 1円未満は四捨五入する。185,000 のように割り切れない額があるため、
 * 足し合わせてから割ると、明細の合計と各行の合計が1円ずれることがある。
 * 合計を出すときは、行ごとに割ってから足すのではなく、
 * 税込のまま足してから最後に1回だけ割ること。
 */
export function exclTax(amount: number): number {
  return Math.round(amount / (1 + TAX_RATE));
}

/** 税別の額から税込の額を出す。 */
export function inclTax(amount: number): number {
  return Math.round(amount * (1 + TAX_RATE));
}
