import type { AgencyRank, CodeKind, SalesChannel } from "./types";

/**
 * 画面に出す「呼び方」を1か所にまとめたファイル。
 *
 * ■ ⚠️ 現状このファイルはどの画面からも呼ばれていない（残作業あり）
 *
 * ここに書いた呼び方は、まだ1つも画面に出ていない。各画面が今も自前で文字を
 * 組み立てているため、下記の差し替えを終えるまで「エリア統括代理店」は表示されない。
 * この節は、差し替えが済んだ時点でまるごと消すこと。
 *
 * 差し替えは (1)(2) をセットで行う前提。片方だけ直すと、同じ代理店が画面ごとに
 * 違う呼ばれ方をする状態が残る。
 *
 * (1) コード区分の呼び方を codeKindLabel() に寄せる ＝ 先に直すべきもの
 *
 *     いま同じ意味の関数が2か所に別実装であり、しかも 00 の呼び方が食い違っている。
 *
 *       src/app/(app)/organization/page.tsx   kindLabel(): 00 →「販売代理店」
 *       src/app/(app)/admin/agencies/[code]/page.tsx
 *                                             kindLabel(): 00 →「会社」
 *
 *     組織図では「販売代理店」、代理店の詳細では「会社」と出るので、同じ相手の肩書きが
 *     画面によって変わる。さらに 00 は総販売代理店・エリア統括代理店・三次のすべてが
 *     使う区分なので、組織図側の「販売代理店」は統括代理店まで販売代理店に見せてしまう
 *     （下の CODE_KIND_LABELS の注意書きが、現に本番画面で起きている）。
 *     この食い違いだけは他より先に揃える。
 *
 * (2) 階層の呼び方を rankLabel() / rankShort() に寄せる
 *
 *       src/app/(app)/dashboard/page.tsx
 *         `const rankLabel = self.rank || self.channel || "ランク未設定"` で
 *         データベースの値をそのままバッジに出しているため、代理店ダッシュボードの
 *         右上は今も「2次代理店」と表示される。ローカル変数名がこの関数と同名なので、
 *         import する際は変数の改名も要る。
 *       src/app/(app)/organization/page.tsx   組織図のランクのバッジ
 *       src/app/(app)/admin/agencies/page.tsx 代理店一覧の「ランク」列（狭いので rankShort）
 *
 *     絞り込み（一覧のランク検索）と並び替えはデータベースの値のままにする。
 *     表示だけを通すこと。理由は下の「使うときの約束」。
 *
 * ■ なぜ必要か
 *
 * 会議で決まった呼び方と、データベースに保存されている値がずれている。
 *
 *   データベースの値   … 総販売代理店 / 2次代理店 / 取次店
 *   会議で使う呼び方   … 総販売代理店 / エリア統括代理店 / 取次店
 *
 * ・2026-06-17 打合せ … 呼称変更を決定。「二次代理店」→「統括代理店」、
 *                        「三次代理店」→「販売代理店」。
 * ・2026-08-07 打合せ … 会話でも資料でも「エリア統括代理店」と呼んでいる。
 *                        JotForm の代理店登録フォームの選択肢も「エリア統括代理店」で、
 *                        それが登録時にデータベースの「2次代理店」に変換されている
 *                        （2026-07-07 に確定したランクの対応どおり）。
 *
 * ■ データベースの値は変えない
 *
 * 保存されている文字列は、過去の受注・報酬・kintone・Make の連携がそのまま参照している。
 * とくに報酬額は「ランクの文字列」で金額の列を選んでいる（src/lib/rewards.ts）ため、
 * 値を書き換えると過去の報酬が引けなくなり、外部連携も一斉に止まる。
 * そこで「保存する値はそのまま、表示だけ新しい呼び方にする」方針にした。
 *
 * ■ 使うときの約束
 *
 * ・画面に文字を出すときだけ、この関数を通す。
 * ・データの絞り込み・分岐・保存には、必ずデータベースの値（"2次代理店" など）を使う。
 *   表示名で比較すると、呼び方が変わった瞬間に条件が効かなくなる。
 * ・この2つを混ぜないこと。
 *
 * ■ 引数を string で受ける理由
 *
 * 呼ぶ側は Agency 型のこともあれば、データベースの行をそのまま持っている画面もある
 * （受注の明細など）。どちらからも書き換えなしで呼べるように、緩く受けて緩く返す。
 * 知らない値が来たら、勝手に決めつけず「未設定」と出す。
 */

/** バッジの色。@/components/ui の Badge の tone にそのまま渡せる。 */
export type LabelTone = "good" | "warn" | "bad" | "neutral";

/* ------------------------------------------------------------------ *
 * 階層（データベースの「ランク」）
 * ------------------------------------------------------------------ */

/**
 * データベースのランク → 画面に出す呼び方。
 *
 * ・総販売代理店 … RIM（株式会社Rimiens）。呼び方は会議でも変わっていないのでそのまま。
 * ・2次代理店   … 2026-06-17 で「統括代理店」に改称。
 *                  2026-08-07 の会話とフォームの表記に合わせて「エリア統括代理店」と出す。
 *                  エリア（関東・九州+沖縄など）ごとに全国60社までという枠の考え方が
 *                  名前から伝わるほうが、本部・代理店どちらの誤解も減る。
 * ・取次店     … データベース上は「三次」の受け皿。呼び方の注意は下の rankLabel を参照。
 *
 * Record 型にしているのは、types.ts に新しいランクが増えたときに
 * ここでコンパイルエラーになって、呼び方の決め忘れに気づけるようにするため。
 */
const RANK_LABELS: Record<AgencyRank, string> = {
  "総販売代理店": "総販売代理店",
  "2次代理店": "エリア統括代理店",
  "取次店": "取次店",
};

/** 表の狭い列に入れるための短い呼び方。 */
const RANK_SHORT_LABELS: Record<AgencyRank, string> = {
  // 「総販売代理店」は縮めると社内でも通じない言い方になるので、そのまま出す。
  "総販売代理店": "総販売代理店",
  // 2026-06-17 の呼称変更どおり「統括代理店」。狭い列では「エリア」を落とす。
  "2次代理店": "統括代理店",
  "取次店": "取次",
};

/**
 * 画面に出す階層の呼び方を返す。
 *
 * ■ コード区分を先に見る理由（重要）
 *
 * 取次パートナー（コード区分 01）とスタッフ（コード区分 02）は、
 * どちらもランクが「取次店」で登録されている。ランクだけを見ると区別がつかない。
 *
 *   取次パートナー … お客様を紹介するだけで、販売はしない。上位の枠は消費しない。
 *   スタッフ       … 代理店に所属する個人。代理店ではないので枠を消費しない。
 *
 * この2つを取り違えると、本部が「販売できる相手」と勘違いして案内してしまったり、
 * 枠の数え方を誤ったりする。だから必ずコード区分を先に見る。
 *
 * ■「取次店」をそのまま出している理由
 *
 * 2026-06-17 に「三次代理店」は「販売代理店」と呼ぶことが決まったが、
 * データベース上の「三次」は 販売代理店 / サロン代理店 / 個人販売パートナー /
 * サロン提携パートナー（取次）の4種類がまとめて「取次店」ランクに入っている。
 * ランクだけを見て「販売代理店」と出すと、サロンや紹介だけの相手まで
 * 販売代理店と表示してしまう。実際にどれなのかは販路種別が持っているので、
 * ランクは「取次店」のまま出し、隣に channelLabel() を並べて表示する。
 *
 * @param rank     データベースの rank 列の値
 * @param codeKind データベースの code_kind 列の値（00=会社 / 01=取次パートナー / 02=スタッフ）
 */
export function rankLabel(
  rank: string | null | undefined,
  codeKind?: string | null,
): string {
  // 取次パートナーとスタッフは、ランクより先にコード区分で見分ける。
  if (codeKind === "01") return "取次パートナー（紹介のみ）";
  if (codeKind === "02") return "スタッフ";

  const hit = RANK_LABELS[(rank ?? "") as AgencyRank];
  if (hit) return hit;

  // 知らない値は、入っている文字をそのまま見せる。
  // 報酬の明細（rewards.agency_rank）には、販路種別を優先した「販売代理店」が
  // 保存されることがある（src/lib/rewards.ts）。3つのランク以外を一律で
  // 「未設定」に潰すと、本部が明細と報酬額の対応を確かめられなくなる。
  const raw = (rank ?? "").trim();
  if (raw) return raw;

  // 本当に空。データが入っていないことを、はっきり書く。
  return "階層未設定";
}

/**
 * 表の狭い列に入れるための短い呼び方。
 * 見分けが必要なところは rankLabel() と同じ順番で判定する。
 */
export function rankShort(
  rank: string | null | undefined,
  codeKind?: string | null,
): string {
  if (codeKind === "01") return "取次";
  if (codeKind === "02") return "スタッフ";

  const hit = RANK_SHORT_LABELS[(rank ?? "") as AgencyRank];
  if (hit) return hit;

  // 知らない値は消さずにそのまま出す（理由は rankLabel と同じ）。
  const raw = (rank ?? "").trim();
  if (raw) return raw;

  return "未設定";
}

/* ------------------------------------------------------------------ *
 * 販路種別
 * ------------------------------------------------------------------ */

/**
 * 販路種別（データベースの channel 列）→ 画面に出す呼び方。
 *
 * 販路種別は「取次店」ランクの中身を分けるためのもので、
 * 上位の枠（統括代理店1社あたり 販売10 / サロン30 / 個人30 / 取次30 = 合計100枠。
 * 2026-07-30 会議で確定）を数える単位でもある。
 *
 * ・販売代理店 … 2026-06-17 に「三次代理店」を言い換えた呼び方。そのまま出す。
 * ・サロン提携パートナー（取次） … 保存値が長いので、画面では
 *   「取次パートナー（紹介のみ）」と出す。販売できる相手だと誤解されるのを防ぐため、
 *   rankLabel() の取次パートナーと同じ言い方で揃えている。
 */
const CHANNEL_LABELS: Record<SalesChannel, string> = {
  "販売代理店": "販売代理店",
  "サロン代理店": "サロン代理店",
  "個人販売パートナー": "個人販売パートナー",
  "サロン提携パートナー（取次）": "取次パートナー（紹介のみ）",
  "未設定": "未設定",
};

/**
 * 販路種別の表示名を返す。
 *
 * 空のときも「未設定」と返すので、呼ぶ側で `|| "—"` を足す必要はない。
 * 販路種別が入っていないと枠をどこにも数えられず運用が詰まるため、
 * 「—」で流すより「未設定」と読ませたほうがよい。
 */
export function channelLabel(channel: string | null | undefined): string {
  const hit = CHANNEL_LABELS[(channel ?? "") as SalesChannel];
  if (hit) return hit;

  // 知らない販路種別も、入っている文字はそのまま見せる。
  // 新しい販路種別が増えたとき、画面から消えると気づけない。
  const raw = (channel ?? "").trim();
  if (raw) return raw;

  return "未設定";
}

/* ------------------------------------------------------------------ *
 * 稼働状況
 * ------------------------------------------------------------------ */

/**
 * 稼働状況に対するバッジの色。
 *
 * データベースの status 列は 未稼働 / 稼働中 / 停止・解約 の3つ。
 * 過去データに「停止」「解約」だけが入っている行があるため、そこも拾う。
 *
 *   稼働中     … good  取引できる状態
 *   未稼働     … warn  登録は済んでいるが、まだ動かせない（研修・署名待ちなど）
 *   停止・解約 … bad   取引が終わっている
 *
 * 「未稼働」を bad にしないのは、これから稼働する相手を
 * 解約した相手と同じ見た目にすると、本部が対応先を見落とすため。
 */
export function statusTone(status: string | null | undefined): LabelTone {
  const s = (status ?? "").trim();
  if (s === "稼働中") return "good";
  if (s === "未稼働") return "warn";
  if (s === "停止・解約" || s === "停止" || s === "解約") return "bad";

  // 空や、まだ知らない状態。色で意味を決めつけない。
  return "neutral";
}

/* ------------------------------------------------------------------ *
 * コード区分
 * ------------------------------------------------------------------ */

/**
 * コード区分（データベースの code_kind 列）→ 画面に出す呼び方。
 *
 * ・00 …「会社」。総販売代理店・エリア統括代理店・三次のいずれも 00 で登録される。
 *        ここを「販売代理店」と書くと、統括代理店まで販売代理店に見えてしまう。
 *        これは注意書きではなく、いま組織図（organization/page.tsx）で実際に起きている。
 *        代理店の詳細画面は同じ 00 を「会社」と出しているので、呼び方も食い違っている。
 *        差し替えの手順はファイル冒頭の残作業を参照。
 *        上位の枠を消費するのはこの 00 だけ（2026-08-07 に枠の数え方として確定）。
 * ・01 …「取次パートナー」。紹介のみ。枠は消費しない。
 * ・02 …「スタッフ」。代理店に所属する個人。枠は消費しない。
 */
const CODE_KIND_LABELS: Record<CodeKind, string> = {
  "00": "会社",
  "01": "取次パートナー",
  "02": "スタッフ",
  "": "区分未設定",
};

/**
 * コード区分の表示名を返す。
 *
 * ランクや販路種別と違い、知らない値（"03" など）が来ても数字は画面に出さない。
 * 数字のままでは読む人に意味が伝わらないので、「区分未設定」として
 * 直してもらうべきデータだと分かるようにする。
 */
export function codeKindLabel(codeKind: string | null | undefined): string {
  const hit = CODE_KIND_LABELS[(codeKind ?? "") as CodeKind];
  if (hit) return hit;

  return "区分未設定";
}

/* ------------------------------------------------------------------ *
 * 代理店種別（申込フォームと同じ言い方）
 * ------------------------------------------------------------------ */

/**
 * 申込フォームの「代理店種別」と、データベースの持ち方の対応。
 *
 * ■ なぜ要るか
 *
 * 本部の画面は「ランク」と「販路種別」を別々の欄で選ばせていた。
 * ところがランクの選択肢はデータベースの値そのままで、
 *
 *   ・申込フォームにある「エリア統括代理店」が出てこない（「2次代理店」と出る）
 *   ・3次の4種類がすべて「取次店」に見え、どれを選べばよいか分からない
 *
 * という状態だった。フォームで選んだ種別が画面に出てこないため、
 * 本部が手で登録するときに元の申込と違う組み合わせを選んでしまう。
 *
 * 申込フォームの4つの選択肢をそのまま1つの欄にして、
 * 保存するときにランクと販路種別へ分けて入れる。
 * データベースの持ち方（rank と channel）は変えていない。
 */
export const AGENCY_TYPES: {
  value: string;
  rank: AgencyRank;
  channel: SalesChannel;
}[] = [
  { value: "エリア統括代理店", rank: "2次代理店", channel: "販売代理店" },
  { value: "販売代理店", rank: "取次店", channel: "販売代理店" },
  { value: "サロン代理店", rank: "取次店", channel: "サロン代理店" },
  { value: "個人販売代理店", rank: "取次店", channel: "個人販売パートナー" },
  { value: "取次パートナー（紹介のみ）", rank: "取次店", channel: "サロン提携パートナー（取次）" },
  { value: "総販売代理店", rank: "総販売代理店", channel: "未設定" },
];

/** ランクと販路種別から、申込フォームと同じ呼び方を返す。 */
export function agencyTypeOf(
  rank: string | null | undefined,
  channel: string | null | undefined,
  codeKind?: string | null,
): string {
  if (codeKind === "02") return "スタッフ";
  const hit = AGENCY_TYPES.find((t) => t.rank === rank && t.channel === channel);
  if (hit) return hit.value;
  // 販路種別が入っていない古いデータは、ランクの呼び方だけで返す
  return rankLabel(rank, codeKind);
}

/** 申込フォームの呼び方から、保存する形（ランクと販路種別）を引く。 */
export function agencyTypeToFields(
  value: string,
): { rank: AgencyRank; channel: SalesChannel } | null {
  const hit = AGENCY_TYPES.find((t) => t.value === value);
  return hit ? { rank: hit.rank, channel: hit.channel } : null;
}
